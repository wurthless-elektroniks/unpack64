'''
Instruction cache clear detection

Looks for osInvalICache(), then looks for calls to it.
If it sees more than one instance of it, suspect the game has more than one code segment.
'''

import struct
from signature import SignatureBuilder
from sigutil import find_all_instances, pick_pattern

OSINVALICACHE_PATTERN = SignatureBuilder() \
    .pattern([
        0x18, 0xa0, 0x00, 0x11,     # blez       a1,LAB_80064c48
        0x00, 0x00, 0x00, 0x00,     # _nop
        0x24, 0x0b, 0x40, 0x00,     # li         t3,0x4000
        0x00, 0xab, 0x08, 0x2b,     # sltu       at,a1,t3
        0x10, 0x20, 0x00, 0x0f,     # beq        at,zero,LAB_80064c50
        0x00, 0x00, 0x00, 0x00,     # _nop
        0x00, 0x80, 0x40, 0x21,     # move       t0,a0
        0x00, 0x85, 0x48, 0x21,     # addu       t1,a0,a1
        0x01, 0x09, 0x08, 0x2b,     # sltu       at,t0,t1
        0x10, 0x20, 0x00, 0x08,     # beq        at,zero,LAB_80064c48
        0x00, 0x00, 0x00, 0x00,     # _nop
        0x25, 0x29, 0xff, 0xe0,     # addiu      t1,t1,-0x20
        0x31, 0x0a, 0x00, 0x1f,     # andi       t2,t0,0x1f
        0x01, 0x0a, 0x40, 0x23,     # subu       t0,t0,t2
        0xbd, 0x10, 0x00, 0x00,     # cache      0x10,0x0(t0)
        0x01, 0x09, 0x08, 0x2b,     # sltu       at,t0,t1
        0x14, 0x20, 0xff, 0xfd,     # bne        at,zero,LAB_80064c38
        0x25, 0x08, 0x00, 0x20,     # _addiu     t0,t0,0x20
        0x03, 0xe0, 0x00, 0x08,     # jr         ra
        0x00, 0x00, 0x00, 0x00,     # _nop
        0x3c, 0x08, 0x80, 0x00,     # lui        t0,0x8000
        0x01, 0x0b, 0x48, 0x21,     # addu       t1,t0,t3
        0x25, 0x29, 0xff, 0xe0,     # addiu      t1,t1,-0x20
        0xbd, 0x00, 0x00, 0x00,     # cache      0x0,0x0(t0)
        0x01, 0x09, 0x08, 0x2b,     # sltu       at,t0,t1
        0x14, 0x20, 0xff, 0xfd,     # bne        at,zero,LAB_80064c5c
        0x25, 0x08, 0x00, 0x20,     # _addiu     t0,t0,0x20
        0x03, 0xe0, 0x00, 0x08,     # jr         ra
        0x00, 0x00, 0x00, 0x00,     # _nop
    ]) \
    .build()

