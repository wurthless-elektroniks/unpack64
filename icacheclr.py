        0x00, 0x00, 0x00, 0x00,     # _nop
        0x00, 0x80, 0x40, 0x25,     # or         t0,a0,zero
        0x00, 0x85, 0x48, 0x21,     # addu       t1,a0,a1
        0x01, 0x09, 0x08, 0x2b,     # sltu       at,t0,t1
        0x10, 0x20, 0x00, 0x08,     # beq        at,zero,LAB_80064c48
        0x00, 0x00, 0x00, 0x00,     # _nop
