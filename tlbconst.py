'''
TLB-related constants
'''


TLB_PAGEMASK_4KBYTES   = (0x0000 << 13) # = 0x00000000
TLB_PAGEMASK_16KBYTES  = (0x0003 << 13)
TLB_PAGEMASK_64KBYTES  = (0x000F << 13)
TLB_PAGEMASK_256KBYTES = (0x003F << 13) # = 0x0007E000
TLB_PAGEMASK_1MBYTES   = (0x00FF << 13) # = 0x001FE000
TLB_PAGEMASK_4MBYTES   = (0x03FF << 13) # = 0x007FE000
TLB_PAGEMASK_16MBYTES  = (0x0FFF << 13)

TLB_PAGEMASK_TO_SIZE_LUT = {
    TLB_PAGEMASK_4KBYTES: 4 * 1024,
    TLB_PAGEMASK_16KBYTES: 16 * 1024,
    TLB_PAGEMASK_64KBYTES: 64 * 1024,
    TLB_PAGEMASK_256KBYTES: 256 * 1024,
    TLB_PAGEMASK_1MBYTES: 1024 * 1024,
    TLB_PAGEMASK_4MBYTES: 4 * 1024 * 1024,
    TLB_PAGEMASK_16MBYTES: 16 * 1024 * 1024
}
